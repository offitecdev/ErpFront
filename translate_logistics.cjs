const fs = require('fs');

const trPath = 'c:/ERP/ErpFront/offitec-frontend/src/i18n/locales/tr.json';
const enPath = 'c:/ERP/ErpFront/offitec-frontend/src/i18n/locales/en.json';
const dePath = 'c:/ERP/ErpFront/offitec-frontend/src/i18n/locales/de.json';

const trData = JSON.parse(fs.readFileSync(trPath, 'utf8'));
const enData = JSON.parse(fs.readFileSync(enPath, 'utf8'));
const deData = JSON.parse(fs.readFileSync(dePath, 'utf8'));

if (!trData.logistics) trData.logistics = {};
if (!enData.logistics) enData.logistics = {};
if (!deData.logistics) deData.logistics = {};

for (const [key, map] of Object.entries(translations)) {
    trData.logistics[key] = map.tr;
    enData.logistics[key] = map.en;
    deData.logistics[key] = map.de;
}

fs.writeFileSync(trPath, JSON.stringify(trData, null, 4), 'utf8');
fs.writeFileSync(enPath, JSON.stringify(enData, null, 4), 'utf8');
fs.writeFileSync(dePath, JSON.stringify(deData, null, 4), 'utf8');

const path = require('path');
const dir = 'c:/ERP/ErpFront/offitec-frontend/src/pages/logistics';
const files = ['ShipmentCreate.tsx', 'Shipments.tsx'];

files.forEach(file => {
    const filepath = path.join(dir, file);
    let content = fs.readFileSync(filepath, 'utf8');
    
    // Replace auto with logistics
    content = content.replace(/t\('auto\./g, "t('logistics.");
    
    // Add reactivity
    if (!content.includes('useLanguageRefresh')) {
        const reactivityCode = `import { useTranslation } from 'react-i18next';

const useLanguageRefresh = () => {
    const { i18n } = useTranslation();
    const [, setTick] = useState(0);
    useEffect(() => {
        const handler = () => setTick(t => t + 1);
        i18n.on('languageChanged', handler);
        return () => i18n.off('languageChanged', handler);
    }, [i18n]);
};`;
        content = content.replace("import { t } from '@/i18n/translate';", "import { t } from '@/i18n/translate';\n" + reactivityCode);
    }

    if (file === 'ShipmentCreate.tsx') {
        content = content.replace("export const ShipmentCreate = ({", "export const ShipmentCreate = ({\n    useLanguageRefresh();");
        // Convert statClass to function
        content = content.replace("const statClass: Record<StatTone, string> = {", "const getStatClass = (): Record<StatTone, string> => ({");
        content = content.replace(/danger: 'bg-red-50 text-red-700 border-red-200',\n};/, "danger: 'bg-red-50 text-red-700 border-red-200',\n});");
        content = content.replace(/className=\{`\$\{statClass/g, "className={`\\${getStatClass()");
    } else if (file === 'Shipments.tsx') {
        content = content.replace("export const Shipments = () => {", "export const Shipments = () => {\n    useLanguageRefresh();");
        // Ensure outside constants that use t are handled
        content = content.replace("const STATUS_LABEL: Record<ShipmentStatus, string> = {", "const getStatusLabel = (): Record<ShipmentStatus, string> => ({");
        content = content.replace(/BILLED:t\('logistics\.faturali'\),\n};/, "BILLED:t('logistics.faturali'),\n});");
        content = content.replace(/STATUS_LABEL\[/g, "getStatusLabel()[");
        content = content.replace(/Object\.entries\(STATUS_LABEL\)/g, "Object.entries(getStatusLabel())");
    }

    fs.writeFileSync(filepath, content, 'utf8');
});

console.log("Done updating JSONs and TSX files");
